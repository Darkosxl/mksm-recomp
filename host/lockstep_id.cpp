bool local_only(const std::string &name) {
    // PS2_NO_VU_THREAD/PS2_THREADS: threaded and single-threaded peers compute the same state (native-lockstep.md);
    // PS2_VU_JIT: the browser's lockstep mode pins it, the desktop has no VU JIT
    // renderer and threading choices (PS2_GS_HW ... PS2_WEB_THREADS): render only, so peers may play at different quality
    static const char *kNames[] = {"PS2_ASPECT", "PS2_FIELD_FLAG", "PS2_SCALE", "PS2_TEX_PACK", "PS2_TEX_PACK_MB", "PS2_TEX_DUMP", "PS2_GS", "PS2_NO_DEINTERLACE",
                                   "PS2_DECODE", "PS2_GPU_FALLBACK", "PS2_GPU_LOW_POWER", "PS2_GPU_PROFILE", "PS2_SDL_RENDERER", "PS2_FPS", "PS2_FPS_CAP",
                                   "PS2_HASH_LOG", "PS2_HASH_LOG_EVERY", "PS2_HASH_SPLIT", "PS2_NO_VU_THREAD", "PS2_THREADS", "PS2_ONE_THREAD",
                                   "PS2_VU_JIT", "PS2_PNACH", "PS2_RTC", "PS2_PROFILE", "PS2_PROFILE_FROM", "PS2_CENSUS", "PS2_DRAW_DUMP",
                                   "PS2_DUMP_AUDIO", "PS2_DUMP_STEMS", "PS2_DUMP_VRAM", "PS2_NETPLAY_ASYNC", "PS2_RASTER_DIAG",
                                   "PS2_GS_HW", "PS2_GS_SPLIT", "PS2_GS_PRIMS", "PS2_SUBMIT_THREAD", "PS2_PIPELINES", "PS2_WEB_THREADS", "PS2_FRAME_LOG"};
    for (const char *n : kNames)
        if (name == n) return true;
    return name.rfind("PS2_TRACE_", 0) == 0 || name.rfind("PS2_LOCKSTEP_", 0) == 0;
}

Identity identity() {
    Identity id;
    id.build = kLockstepBuildId;
    // game patch set: PS2_PNACH files (apply_pnach) by content, in order; they change what the game computes
    id.patch_files = Json::array();
    std::string patches = "none";
    if (const char *spec = std::getenv("PS2_PNACH"); spec && *spec) {
        std::vector<std::uint8_t> all, bytes;
        const std::string list = spec;
        for (std::size_t at = 0; at < list.size();) {
            const std::size_t end = std::min(list.find(',', at), list.size());
            const std::string file = list.substr(at, end - at);
            at = end + 1;
            if (!read_file(file, bytes)) {
                id.error = "cannot read the game patch " + file;
                return id;
            }
            const std::uint64_t size = bytes.size();
            all.insert(all.end(), reinterpret_cast<const std::uint8_t *>(&size), reinterpret_cast<const std::uint8_t *>(&size) + 8);
            all.insert(all.end(), bytes.begin(), bytes.end());
            id.patch_files.push(basename(file));
        }
        patches = hex16(ps2::hash_bytes(all.data(), all.size()));
    }
    std::vector<std::string> env;
    for (char **e = environ; e && *e; ++e) {
        const std::string kv = *e;
        if (kv.rfind("PS2_", 0) == 0 && !local_only(kv.substr(0, kv.find('=')))) env.push_back(kv);
    }
    std::sort(env.begin(), env.end());
    Json env_json = Json::array();
    for (const std::string &kv : env) env_json.push(kv);
    const char *rate = ps2::g_options.rate_forced ? (ps2::g_options.pal ? "pal" : "ntsc") : "auto";
    // no start state: the guest drops into the host's game (W4), whatever it booted from
    id.config = Json::object().set("lockstep", 1).set("rate", rate).set("patches", patches).set("env", env_json);
    return id;
}

